<script>
document.addEventListener('DOMContentLoaded', function () {

  var leftEls = document.querySelectorAll('.mod-reveal-left');
  var rightEls = document.querySelectorAll('.mod-reveal-right');

  leftEls.forEach(function (el) {
    el.style.opacity = '0';
    el.style.transform = 'translateX(-40px)';
    el.style.transition = 'all 0.8s cubic-bezier(0.4, 0, 0.2, 1)';
  });

  rightEls.forEach(function (el) {
    el.style.opacity = '0';
    el.style.transform = 'translateX(40px)';
    el.style.transition = 'all 0.8s cubic-bezier(0.4, 0, 0.2, 1) 0.2s';
  });

  var modObserver = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        entry.target.style.opacity = '1';
        entry.target.style.transform = 'translateX(0)';
        modObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });

  leftEls.forEach(function (el) { modObserver.observe(el); });
  rightEls.forEach(function (el) { modObserver.observe(el); });

  var progressBar = document.querySelector('.mod-progress-bar');
  if (progressBar) {
    var progObserver = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          setTimeout(function () {
            progressBar.style.width = '90%';
          }, 400);
          progObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.3 });

    progObserver.observe(progressBar);
  }
});
</script>